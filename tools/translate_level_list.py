LINE_RE = re.compile(r'^(m_levelName\[(\d+)\]=").*$' , re.MULTILINE)


def normalize_display_punctuation(text: str) -> str:
    # The patched PC font maps ASCII punctuation but does not map the
    # full-width variants used by the original level names.
    replacements = {
        0x2026: "...",
        0x203B: "*",
        0x300A: "<",
        0x300B: ">",
        0xFF01: "!",
        0xFF06: "&",
        0xFF08: "(",
        0xFF09: ")",
        0xFF0C: ",",
        0xFF1A: ":",
        0xFF1F: "?",
    }
    return text.translate(replacements)


def translate(text: str) -> str:
    seen = set()

    def replace(match: re.Match[str]) -> str:
        index = int(match.group(2))
        if index not in TRANSLATIONS:
            raise RuntimeError(f"Missing translation for level {index}")
        seen.add(index)
        return f'{match.group(1)}{TRANSLATIONS[index]}"'

    result = LINE_RE.sub(replace, text)
    result = normalize_display_punctuation(result)
    if seen != set(TRANSLATIONS):
        missing = sorted(set(TRANSLATIONS) - seen)
        raise RuntimeError(f"Unexpected level list coverage; missing lines: {missing}")
    if re.search(r'[\u3040-\u30ff]', result):
        raise RuntimeError("Japanese kana remains in levelList")
    return result


def main() -> None:
    for game_path in FILES:
        raw = game_path.read_bytes()
        text = raw.decode("utf-16")
        translated = translate(text)
        game_path.write_text(translated, encoding="utf-16")
        patch_path = PATCH_ROOT / game_path.relative_to(GAME_ROOT)
        patch_path.parent.mkdir(parents=True, exist_ok=True)
        patch_path.write_text(translated, encoding="utf-16")
        print(f"translated {game_path}")


if __name__ == "__main__":
    main()
